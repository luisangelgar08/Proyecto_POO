    public Alumno buscarAlumno(ArrayList<Alumno> dato,
                          int codigoDado) {

    for (int i = 0; i < dato.size(); i++) {

        Alumno obj = dato.get(i);

        if (obj.getCodigo() == codigoDado) {
            return obj;
        }
    }

    return null;
    }

